class GenerationTestCase(BspTestCase):
    """带常用模块的 BSP，以及生成和取报错的辅助。
    A BSP with common Modules, and helpers that generate and collect errors.
    """

    def setUp(self):
        super().setUp()
        self.module("Led", LED)
        self.module("Probe", PROBE)
        self.module("Cmd", CMD)
        self.entry(REGISTERED)

    def code(self, *instances, **top):
        """用这些实例生成头文件并返回其文本。
        Generate the header with these instances and return its text.
        """
        top["modules"] = list(instances)
        return self.generate(top)

    def error(self, *instances, **top):
        """用这些实例生成头文件，返回报错文本。
        Generate the header with these instances and return the error text.
        """
        top["modules"] = list(instances)
        with self.assertRaises(ValueError) as context:
            self.generate(top)
        return str(context.exception)


class HeaderShape(GenerationTestCase):
    """生成头文件的结构。
    The structure of the generated header.
    """

    def test_the_complete_header_of_one_instance(self):
        code = self.code(
            led(),
            constexprs={"Rate": {"type": "int", "value": "1000"}},
            settings={"monitor_sleep_ms": "5"},
        )
        digest = read_header_inputs(self.root / "User/xrobot_main.hpp").digest
        self.assertEqual(
            code,
            f"""// Generated by `xrobot gen` from User/xrobot.yaml; do not edit by hand.
#pragma once

#include "Led.hpp"
#include "libxr.hpp"
#include "thread.hpp"

namespace ProjectConstexpr
{{
inline constexpr int Rate = 1000;
}}  // namespace ProjectConstexpr

[[noreturn]] static inline void XRobotMain(LibXR::GPIO& pin)
{{
  // led: team/Led (xrobot.yaml:8)
#line 8 "xrobot.yaml"
  static const Led::Param xr_led_param = {{
      .cycle = 250,
      .inverted = false,
  }};
  static Led led(pin, xr_led_param, 1.0f);
#line 23 "xrobot_main.hpp"

  for (;;)
  {{
    led.OnMonitor();
    LibXR::Thread::Sleep(5);
  }}
}}

// XR_REGISTER marks a name for the generator; XRobotMain binds and type-checks it.
#define XR_REGISTER(name, ...) static_cast<void>(name)
#define XROBOT_MAIN() ::XRobotMain(pin)

// xrobot: config "xrobot.yaml"
// xrobot: depends "../xrobot.lock"
// xrobot: entry "app_main.cpp"
// xrobot: depends "../Modules/team/Cmd/Cmd.hpp"
// xrobot: depends "../Modules/team/Led/Led.hpp"
// xrobot: depends "../Modules/team/Probe/Probe.hpp"
// xrobot: digest {digest}
""",
        )

    def test_the_banner_names_the_config_and_the_input_list_ends_the_file(self):
        lines = self.code(led()).split("\n")
        self.assertEqual(lines[:2], [header_banner("User/xrobot.yaml"), "#pragma once"])
        self.assertEqual(lines[-8], '// xrobot: config "xrobot.yaml"')
        self.assertTrue(lines[-2].startswith("// xrobot: digest "))
        self.assertEqual(lines[-1], "")
        self.assertEqual(self.project.header_selection(), self.root / "User/xrobot.yaml")
        self.assertEqual(self.project.header_state()["status"], "fresh")

    def test_a_long_banner_is_wrapped_into_comment_lines_within_the_column_limit(self):
        name = "products/" + "x" * 40 + ".yaml"
        self.generate({"modules": [led()]}, name=name)
        lines = self.read("User/xrobot_main.hpp").split("\n")
        banner = lines[: lines.index("#pragma once")]
        self.assertEqual(len(banner), 2)
        self.assertTrue(all(len(line) <= 90 and line.startswith("// ") for line in banner))
        self.assertEqual(
            " ".join(line[3:] for line in banner),
            f"Generated by `xrobot gen` from User/{name}; do not edit by hand.",
        )

    def test_each_instance_has_a_comment_with_its_module_and_yaml_line(self):
        self.module(
            "Buf",
            "template <typename T, unsigned N = 4>\n"
            "class Buf { public: explicit Buf(T init = T{}) {} };",
        )
