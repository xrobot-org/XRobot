    def test_entry_function_takes_only_consumed_registrations(self):
        code = self.code(led())
        self.assertIn("[[noreturn]] static inline void XRobotMain(LibXR::GPIO& pin)\n{", code)
        self.assertIn("\n#define XROBOT_MAIN() ::XRobotMain(pin)\n", code)
        for name in ("uart", "unused", "hidden", "port"):
            self.assertNotRegex(code, rf"\b{name}\b")

    def many_registrations(self, count):
        """一个用到 count 个注册的配置生成的头文件文本。
        The header of a configuration that uses count registrations.
        """
        names = [f"gpio_{i}" for i in range(count)]
        self.entry(
            '#include "xrobot_main.hpp"\nint main() {\n'
            + "".join(f"  XR_REGISTER({name}, LibXR::GPIO);\n" for name in names)
            + "  XROBOT_MAIN();\n}\n"
        )
        return self.code(*[led(f"led_{i}", gpio=name) for i, name in enumerate(names)])

    def test_a_long_entry_function_aligns_its_parameters_after_the_parenthesis(self):
        code = self.many_registrations(14)
        indent = " " * 43
        self.assertIn(
            "[[noreturn]] static inline void XRobotMain(LibXR::GPIO& gpio_0, LibXR::GPIO& gpio_1,\n"
            + indent
            + "LibXR::GPIO& gpio_2, LibXR::GPIO& gpio_3,\n",
            code,
        )
        self.assertIn(indent + "LibXR::GPIO& gpio_12, LibXR::GPIO& gpio_13)\n{\n", code)

    def test_a_very_long_entry_function_breaks_after_the_parenthesis(self):
        code = self.many_registrations(30)
        self.assertIn(
            "[[noreturn]] static inline void XRobotMain(\n"
            "    LibXR::GPIO& gpio_0, LibXR::GPIO& gpio_1, LibXR::GPIO& gpio_2, "
            "LibXR::GPIO& gpio_3,\n",
            code,
        )
        self.assertIn("LibXR::GPIO& gpio_29)\n{\n", code)

    def test_a_long_macro_wraps_at_the_column_limit_with_aligned_continuations(self):
        code = self.many_registrations(14)
        macro = code[code.index("#define XROBOT_MAIN()") :].split("\n\n")[0].split("\n")
        self.assertEqual(macro[0].split()[:2], ["#define", "XROBOT_MAIN()"])
        self.assertTrue(macro[1].startswith("  ::XRobotMain(gpio_0, gpio_1, "))
        self.assertTrue(macro[-1].endswith("gpio_13)"))
        # 续行符对齐在同一列，每行不超过 90 个字符。
        # The line continuations share one column, and no line is longer than 90 characters.
        self.assertEqual({len(line) for line in macro[:-1]}, {len(macro[0])})
        for line in code.split("\n"):
            if not line.startswith("// xrobot:"):
                self.assertLessEqual(len(line), 90, line)

