class Monitors(BspTestCase):
    """生成的主循环调用哪些 OnMonitor。
    Which OnMonitor functions the generated main loop calls.
    """

    def setUp(self):
        super().setUp()
        self.entry(MAIN)

    def monitored(self, body, name="M"):
        """生成的主循环是否调用这个类的 OnMonitor。
        Whether the generated main loop calls OnMonitor of this class.
        """
        self.module(name, body)
        code = self.generate({"modules": [{"module": name, "id": "m"}]})
        return "m.OnMonitor();" in code

    def test_a_public_monitor_is_called(self):
        self.assertTrue(self.monitored("class M { public: M() {} void OnMonitor() {} };"))

    def test_calling_a_members_monitor_does_not_make_the_class_monitored(self):
        # 成员函数里调用成员的 OnMonitor() 不等于类自己声明了 OnMonitor：循环不会调用它，
        # 也不会为它写 static_assert。
        # Calling the OnMonitor() of a member inside a member function does not mean the class
        # declares OnMonitor: the loop does not call it and no static_assert is written.
        self.module("Sensor", "class Sensor { public: Sensor() {} void OnMonitor() {} };")
        calling = (
            '#include "Sensor.hpp"\nclass M { public: M() {}\n'
            "  void Update() { sensor_.OnMonitor(); }\n private:\n  Sensor sensor_;\n};"
        )
        self.assertFalse(self.monitored(calling))
        declaring = calling.replace("void Update()", "void OnMonitor()")
        self.assertTrue(self.monitored(declaring))
        self.assertNotIn("static_assert", self.generate({"modules": [{"module": "M", "id": "m"}]}))

    def test_a_private_or_missing_monitor_is_not_called(self):
        self.assertFalse(self.monitored("class M { public: M() {} private: void OnMonitor() {} };"))
        self.assertFalse(self.monitored("class M { public: M() {} };"))

    def test_a_monitor_inherited_from_a_module_base_is_called(self):
        self.assertTrue(
            self.monitored(
                "struct Core { void OnMonitor() {} };\nclass M : public Core { public: M() {} };"
            )
        )
        self.assertFalse(
            self.monitored(
                "struct Core { void OnMonitor() {} };\nclass M : Core { public: M() {} };"
            )
        )

    def test_an_unlocatable_public_base_is_an_error(self):
        self.module("M", "class M : public Vendor::Base { public: M() {} };")
        with self.assertRaisesMessage(
            ConfigError,
            "User/xrobot.yaml: m: cannot tell whether a public base class provides OnMonitor; "
            "its base is not defined in the loaded Module headers",
        ):
            self.generate({"modules": [{"module": "M", "id": "m"}]})

    def test_a_conditional_monitor_is_an_error(self):
        self.module("M", "class M { public: M() {}\n#if FEATURE\n  void OnMonitor() {}\n#endif\n};")
        with self.assertRaisesMessage(
            ValueError,
            "User/xrobot.yaml: m: M declares OnMonitor under #if; the generator cannot "
            "evaluate build options",
        ):
            self.generate({"modules": [{"module": "M", "id": "m"}]})

    def test_a_result_that_is_certainly_not_void_is_an_error_at_generation(self):
        for returned in ("int", "bool", "unsigned long", "std::uint8_t", "void*", "const char*"):
            with self.subTest(returned=returned):
                self.module(
                    "M",
                    "#include <cstdint>\nclass M { public: M() {} "
                    f"{returned} OnMonitor() {{ return {{}}; }} }};",
                )
                with self.assertRaisesMessage(
                    ValueError,
                    f"User/xrobot.yaml: m: OnMonitor of M returns {returned}; it must return void",
                ):
                    self.generate({"modules": [{"module": "M", "id": "m"}]})

    def test_a_known_void_result_needs_no_assertion(self):
        for declaration in (
            "void OnMonitor() {}",
            "virtual void OnMonitor() {}",
            "[[maybe_unused]] static inline void OnMonitor() {}",
            "void OnMonitor() const noexcept {}",
        ):
            with self.subTest(declaration=declaration):
                self.module("M", f"class M {{ public: M() {{}} {declaration} }};")
                code = self.generate({"modules": [{"module": "M", "id": "m"}]})
                self.assertIn("m.OnMonitor();", code)
                self.assertNotIn("static_assert", code)

    def test_a_result_the_index_cannot_read_keeps_one_compact_assertion(self):
        # 返回类型是别名、auto、尾置返回类型，或各重载写法不一，或来自 using 声明：
        # 生成时无法判断，由编译器检查。
        # An alias, auto, a trailing return type, overloads that disagree, or a using
        # declaration: generation cannot tell, and the compiler checks.
        for body in (
            "using Result = void;\n  Result OnMonitor() {}",
            "auto OnMonitor() {}",
            "auto OnMonitor() -> void {}",
            "void OnMonitor() {}\n  int OnMonitor(int) { return 0; }",
        ):
            with self.subTest(body=body):
                self.module("M", f"class M {{ public: M() {{}}\n  {body}\n}};")
                code = self.generate({"modules": [{"module": "M", "id": "m"}]})
                self.assertEqual(code.count("static_assert"), 1)
                self.assertIn(
                    "  static_assert(std::is_void_v<decltype(m.OnMonitor())>,\n"
                    '                "m.OnMonitor() must return void");\n',
                    code,
                )
                self.assertIn("#include <type_traits>\n", code)

    def test_the_result_of_an_inherited_monitor_is_read_from_its_base(self):
        self.module(
            "M",
            "struct Core { int OnMonitor() { return 1; } };\nclass M : public Core { public: M() {} };",
        )
        with self.assertRaisesMessage(
            ValueError, "User/xrobot.yaml: m: OnMonitor of M returns int; it must return void"
        ):
            self.generate({"modules": [{"module": "M", "id": "m"}]})
        self.module(
            "M", "struct Core { void OnMonitor() {} };\nclass M : public Core { public: M() {} };"
        )
        self.assertNotIn("static_assert", self.generate({"modules": [{"module": "M", "id": "m"}]}))


